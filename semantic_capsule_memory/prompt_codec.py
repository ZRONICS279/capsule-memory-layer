"""Prompt codecs for compiled Capsule memory payloads.

The codecs operate only on prompt scaffolding generated by this package. They
do not summarize, rank, drop, or rewrite fact values; the full ledger remains in
storage and exact evidence can still be expanded by source id.
"""

from __future__ import annotations

from dataclasses import dataclass
import re

from .budget import estimate_tokens


FACT_EVIDENCE_RE = re.compile(r"\s+evidence=([0-9a-f]{16}:[A-Za-z0-9_.-]+:[A-Za-z0-9_.-]+)")
FACT_LINE_RE = re.compile(
    r"^-\s+(?P<scope>[A-Za-z0-9_.-]+)\.(?P<key>[A-Za-z0-9_.-]+)="
    r"(?P<value>.*?)\s+evidence=(?P<evidence>[0-9a-f]{16}:[A-Za-z0-9_.-]+:[A-Za-z0-9_.-]+)"
    r"(?P<suffix>.*)$"
)
RETRIEVED_EVIDENCE_RE = re.compile(r"\bevidence=([0-9a-f]{16})\b")
MEMORY_HANDLE_RE = re.compile(r"^MEMORY_HANDLE\s+(\S+)\s+id=(\S+)\s+v=(\d+)$")
TARGET_FILE_KEYS = {"created_file", "edit_file", "route_file"}
GROUPABLE_FACT_KEYS = {
    "accepted_decision",
    "active_auth_middleware",
    "config_key",
    "endpoint",
    "feature_flag",
    "final_value",
    "function_name",
    "on_call_owner",
    "package",
    "pagination_mode",
    "schema_version",
    "timeout_seconds",
    "version",
}


@dataclass(frozen=True)
class EncodedPrompt:
    payload: str
    token_estimate: int
    evidence_refs: dict[str, str]


@dataclass(frozen=True)
class _FactLine:
    raw: str
    scope: str
    key: str
    value: str
    evidence: str
    source: str
    suffix: str
    file_path: str = ""


def encode_prompt(payload: str, *, codec: str = "verbose") -> EncodedPrompt:
    """Encode a compiled memory prompt for model injection.

    ``verbose`` preserves the input exactly. ``compact`` shortens known Capsule
    scaffolding and long evidence handles while preserving fact values.
    """

    if codec == "verbose":
        return EncodedPrompt(payload=payload, token_estimate=estimate_tokens(payload), evidence_refs={})
    if codec == "compact":
        return _compact_memory_prompt(payload)
    raise ValueError(f"unknown prompt codec {codec!r}; expected 'verbose' or 'compact'")


def compact_memory_prompt(payload: str) -> str:
    """Shrink a Capsule prompt without changing selected facts."""

    return _compact_memory_prompt(payload).payload


def _compact_memory_prompt(payload: str) -> EncodedPrompt:
    """Shrink a Capsule prompt and return its sidecar local evidence map."""

    if not payload:
        return EncodedPrompt(payload=payload, token_estimate=0, evidence_refs={})

    local_refs: dict[str, str] = {}
    evidence_refs: dict[str, str] = {}
    compact_lines: list[str] = []
    in_retrieved = False
    active_facts: list[str] = []

    def flush_active_facts() -> None:
        if not active_facts:
            return
        compact_lines.extend(
            _compact_active_facts(
                active_facts,
                local_refs=local_refs,
                evidence_refs=evidence_refs,
            )
        )
        active_facts.clear()

    for raw_line in payload.splitlines():
        line = raw_line.strip()
        if not line:
            continue

        handle = MEMORY_HANDLE_RE.match(line)
        if handle:
            label, _capsule_id, version = handle.groups()
            compact_lines.append(f"MEM {label} v{version}")
            continue
        if line == "RULE active facts only; UNKNOWN if absent; CONFLICT if facts disagree.":
            compact_lines.append("RULE active-only; UNKNOWN if absent; CONFLICT if disagree.")
            continue
        if line == "ACTIVE_FACTS:":
            compact_lines.append("ACTIVE_FACTS:")
            active_facts.clear()
            continue
        if line == "TASK_STATE:":
            flush_active_facts()
            compact_lines.append("STATE:")
            in_retrieved = False
            continue
        if line == "PATCH_CHECKLIST:":
            flush_active_facts()
            compact_lines.append("PATCH:")
            in_retrieved = False
            continue
        if line == "RETRIEVED_EVIDENCE:":
            flush_active_facts()
            compact_lines.append("EVID:")
            in_retrieved = True
            continue
        if line == "DO_NOT_USE:":
            flush_active_facts()
            compact_lines.append(line)
            continue
        if line.startswith("OMITTED_FACTS "):
            flush_active_facts()
            omitted = line.split(";", 1)[0].replace("OMITTED_FACTS", "OMIT", 1)
            compact_lines.append(f"{omitted}; retrieve exact evidence if needed.")
            continue
        if line == "RESPONSE_RULE use exact active values; do not infer missing names/numbers/versions.":
            flush_active_facts()
            compact_lines.append("RESP exact active values; do not infer missing.")
            continue

        if line.startswith("- ") and not in_retrieved:
            active_facts.append(line)
            continue

        flush_active_facts()
        line = _compact_line(
            line,
            local_refs=local_refs,
            evidence_refs=evidence_refs,
            in_retrieved=in_retrieved,
        )
        if line:
            compact_lines.append(line)

    flush_active_facts()
    compact = "\n".join(compact_lines)
    return EncodedPrompt(payload=compact, token_estimate=estimate_tokens(compact), evidence_refs=evidence_refs)


def _compact_active_facts(
    lines: list[str],
    *,
    local_refs: dict[str, str],
    evidence_refs: dict[str, str],
) -> list[str]:
    facts = [_parse_fact_line(line) for line in lines]
    by_source: dict[str, list[int]] = {}
    for index, fact in enumerate(facts):
        if fact is not None:
            by_source.setdefault(fact.source, []).append(index)

    grouped: dict[int, str] = {}
    used: set[int] = set()
    for source, indexes in by_source.items():
        source_facts = [facts[index] for index in indexes]
        parsed = [fact for fact in source_facts if fact is not None]
        file_facts = [
            fact for fact in parsed
            if _fact_target_file(fact) and _groupable_suffix(fact)
        ]
        unique_files = tuple(dict.fromkeys(_fact_target_file(fact) for fact in file_facts if _fact_target_file(fact)))
        if len(unique_files) != 1:
            continue

        detail_facts = [
            (index, facts[index])
            for index in indexes
            if facts[index] is not None
            and facts[index].key in GROUPABLE_FACT_KEYS
            and _groupable_suffix(facts[index])
            and (not facts[index].file_path or facts[index].file_path == unique_files[0])
        ]
        if not detail_facts:
            continue

        ref = _local_ref(source, local_refs=local_refs, evidence_refs=evidence_refs)
        details = "; ".join(f"{_display_key(fact.key)}={fact.value}" for _index, fact in detail_facts if fact is not None)
        consumed = {index for index, _fact in detail_facts}
        consumed.update(index for index in indexes if facts[index] in file_facts and facts[index].key in TARGET_FILE_KEYS)
        grouped[min(consumed)] = f"- {unique_files[0]}: {details} {ref}"
        used.update(consumed)

    all_file_facts = [
        (index, fact)
        for index, fact in enumerate(facts)
        if fact is not None
        and _fact_target_file(fact)
        and _groupable_suffix(fact)
    ]
    unique_files = tuple(dict.fromkeys(_fact_target_file(fact) for _index, fact in all_file_facts if _fact_target_file(fact)))
    if len(unique_files) == 1:
        detail_facts = [
            (index, fact)
            for index, fact in enumerate(facts)
            if index not in used
            and fact is not None
            and fact.key in GROUPABLE_FACT_KEYS
            and _groupable_suffix(fact)
            and (not fact.file_path or fact.file_path == unique_files[0])
        ]
        remaining_file_indexes = {
            index
            for index, fact in all_file_facts
            if index not in used and fact.key in TARGET_FILE_KEYS
        }
        if detail_facts and (remaining_file_indexes or any(fact.file_path for _index, fact in detail_facts)):
            details = "; ".join(
                f"{_display_key(fact.key)}={fact.value} "
                f"{_local_ref(fact.evidence, local_refs=local_refs, evidence_refs=evidence_refs)}"
                for _index, fact in detail_facts
            )
            consumed = {index for index, _fact in detail_facts}
            consumed.update(remaining_file_indexes)
            grouped[min(consumed)] = f"- {unique_files[0]}: {details}"
            used.update(consumed)

    compacted: list[str] = []
    # Preserve the compiler's ranking order: emit a grouped line where its first
    # consumed fact appeared, then compact all remaining facts in original order.
    for index, line in enumerate(lines):
        if index in grouped:
            compacted.append(grouped[index])
            continue
        if index in used:
            continue
        compacted.append(_compact_line(line, local_refs=local_refs, evidence_refs=evidence_refs, in_retrieved=False))
    return compacted


def _parse_fact_line(line: str) -> _FactLine | None:
    match = FACT_LINE_RE.match(line)
    if not match:
        return None
    evidence = match.group("evidence")
    return _FactLine(
        raw=line,
        scope=match.group("scope"),
        key=match.group("key"),
        value=match.group("value").strip(),
        evidence=evidence,
        source=evidence.split(":", 1)[0],
        suffix=match.group("suffix"),
        file_path=_suffix_file_path(match.group("suffix")),
    )


def _looks_like_file_path(value: str) -> bool:
    return bool(re.search(r"(?:^|/)[A-Za-z0-9_.-]+\.[A-Za-z0-9_]+$", value))


def _suffix_file_path(suffix: str) -> str:
    match = re.search(r"(?:^|\s)file=([^\s]+)", suffix)
    if not match:
        return ""
    value = match.group(1).strip("`'\".,;:)")
    return value if _looks_like_file_path(value) else ""


def _suffix_without_file(suffix: str) -> str:
    return re.sub(r"(?:^|\s)file=[^\s]+", " ", suffix).strip()


def _groupable_suffix(fact: _FactLine | None) -> bool:
    return fact is not None and not _suffix_without_file(fact.suffix)


def _fact_target_file(fact: _FactLine) -> str:
    if fact.file_path:
        return fact.file_path
    if fact.key in TARGET_FILE_KEYS and _looks_like_file_path(fact.value):
        return fact.value
    return ""


def _display_key(key: str) -> str:
    if key in {"active_auth_middleware", "on_call_owner", "pagination_mode", "timeout_seconds"}:
        return key.upper()
    return key


def _compact_line(
    line: str,
    *,
    local_refs: dict[str, str],
    evidence_refs: dict[str, str],
    in_retrieved: bool,
) -> str:
    prefix = "- " if line.startswith("- ") else ""
    if prefix:
        line = line[2:]

    def evidence_ref(match: re.Match[str]) -> str:
        evidence = match.group(1)
        ref = _local_ref(evidence, local_refs=local_refs, evidence_refs=evidence_refs)
        return f" {ref}"

    if in_retrieved:
        line = RETRIEVED_EVIDENCE_RE.sub(lambda match: _local_ref(match.group(1), local_refs=local_refs, evidence_refs=evidence_refs), line)
        line = line.replace(" score=", " s=")
    else:
        line = FACT_EVIDENCE_RE.sub(evidence_ref, line)
    line = line.replace("CURRENT_FOCUS paths=", "FOCUS ")
    line = line.replace(
        "GROUNDING_RULE assistant_claim_not_proof; for file existence or edits, inspect the repo before claiming success.",
        "GROUND inspect repo before file/edit claims.",
    )
    line = line.replace("assistant_claim_not_proof", "claim_not_proof")
    return f"{prefix}{line}"


def _local_ref(evidence: str, *, local_refs: dict[str, str], evidence_refs: dict[str, str]) -> str:
    ref = local_refs.get(evidence)
    if ref is None:
        ref = f"#e{len(local_refs) + 1}"
        local_refs[evidence] = ref
        evidence_refs[ref] = evidence.split(":", 1)[0]
    return ref
